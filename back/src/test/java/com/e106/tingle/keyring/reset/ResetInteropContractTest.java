	private static Properties vectors(String resource) throws Exception {
		var properties = new Properties();
		try (var input = ResetInteropContractTest.class.getResourceAsStream(resource)) {
			assertThat(input).isNotNull();
			properties.load(input);
		}
		return properties;
	}

	private static PublicKey publicKey(String raw) {
		try {
			byte[] prefix = HexFormat.of().parseHex("302a300506032b6570032100");
			byte[] spki = new byte[44];
			System.arraycopy(prefix, 0, spki, 0, prefix.length);
			System.arraycopy(Base64.getUrlDecoder().decode(raw), 0, spki, prefix.length, 32);
			return KeyFactory.getInstance("Ed25519").generatePublic(new X509EncodedKeySpec(spki));
		} catch (Exception exception) {
			throw new AssertionError("Invalid public firmware fixture", exception);
		}
	}

	private static void assertSignedFields(String rawKey, String text, String proof) throws Exception {
		var key = publicKey(rawKey);
		assertThat(verifies(key, bytes(text), proof)).isTrue();
		assertThat(verifies(key, bytes(text.substring(0, text.length() - 1)), proof)).isFalse();
		assertThat(verifies(key, bytes(text.replace("\n", "\r\n")), proof)).isFalse();
		String[] fields = text.split("\n");
		for (int index = 0; index < fields.length; index++) {
			String[] changed = fields.clone();
			changed[index] += "0";
			assertThat(verifies(key, bytes(String.join("\n", changed) + "\n"), proof))
				.as("firmware signed field %s", index).isFalse();
		}
	}

	private static boolean verifies(PublicKey key, byte[] bytes, String proof) throws Exception {
		var verifier = Signature.getInstance("Ed25519");
		verifier.initVerify(key);
		verifier.update(bytes);
		return verifier.verify(Base64.getUrlDecoder().decode(proof));
	}

	private static byte[] bytes(String text) {
		return text.getBytes(StandardCharsets.UTF_8);
	}

	private static String encode(byte[] bytes) {
		return Base64.getUrlEncoder().withoutPadding().encodeToString(bytes);
	}
