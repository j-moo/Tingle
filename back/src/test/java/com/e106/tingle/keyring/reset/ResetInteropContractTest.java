	@Test
	void actualCSettingsV2SignerMatchesBackendAndBindsEpochAgainstDowngrade() throws Exception {
		var vectors = vectors("/keyring/settings-firmware-f701140d.properties");
		String proof = vectors.getProperty("serverSettingsV2");
		assertThat(settings(vectors, 1L).bytes()).isEqualTo(bytes(SETTINGS_V2_TEXT));
		assertSignedFields(vectors.getProperty("serverPublicKey"), SETTINGS_V2_TEXT, proof);
		var key = publicKey(vectors.getProperty("serverPublicKey"));
		assertThat(verifies(key, settings(vectors, 0L).bytes(), proof)).isFalse();
		assertThat(verifies(key, settings(vectors, null).bytes(), proof)).isFalse();
	}

	@Test
	void firmwareRegistrationAndStoredV2BindExactEpochAndRejectV1Downgrade() throws Exception {
		var vectors = vectors();
		var registration = KeyringProofTranscript.registrationV2("synthetic-key", "synthetic-device",
			UUID.fromString(RUN), NONCE, 1793577900, 1);
		var stored = KeyringProofTranscript.storedV2("synthetic-key", "synthetic-device", 4,
			UUID.fromString(NEXT_OWNER), UUID.fromString(RUN), NONCE, 1, vectors.getProperty("hash"), 1);
		assertThat(registration.bytes()).isEqualTo(bytes(REGISTRATION_V2_TEXT));
		assertThat(stored.bytes()).isEqualTo(bytes(STORED_V2_TEXT));
		assertSignedFields(vectors.getProperty("publicKey"), REGISTRATION_V2_TEXT,
			vectors.getProperty("registration"));
		assertSignedFields(vectors.getProperty("publicKey"), STORED_V2_TEXT, vectors.getProperty("stored"));
		var key = publicKey(vectors.getProperty("publicKey"));
		assertThat(verifies(key, KeyringProofTranscript.registration("synthetic-key", "synthetic-device",
			UUID.fromString(RUN), NONCE, 1793577900).bytes(), vectors.getProperty("registration"))).isFalse();
		assertThat(verifies(key, KeyringProofTranscript.stored("synthetic-key", "synthetic-device", 4,
			UUID.fromString(NEXT_OWNER), UUID.fromString(RUN), NONCE, 1, vectors.getProperty("hash")).bytes(),
			vectors.getProperty("stored"))).isFalse();
	}

	@Test
	void firmwareSignaturesAndExactFinalLfMatchAllThreeTranscripts() throws Exception {
		var vectors = vectors();
		var challenge = challenge(vectors);
		var context = context(vectors, 0, OWNER, false, NONCE);
		assertThat(SignedResetDeviceProtocol.challengeTranscript(challenge)).isEqualTo(bytes(CHALLENGE_TEXT));
		assertThat(SignedResetDeviceProtocol.authorizationTranscript(context, "synthetic-server"))
			.isEqualTo(bytes(AUTH_TEXT));
		assertThat(SignedResetDeviceProtocol.clearedTranscript(context)).isEqualTo(bytes(CLEARED_TEXT));
		assertSignedFields(vectors.getProperty("publicKey"), CHALLENGE_TEXT, vectors.getProperty("challenge"));
		assertSignedFields(vectors.getProperty("serverPublicKey"), AUTH_TEXT, vectors.getProperty("authorization"));
		assertSignedFields(vectors.getProperty("publicKey"), CLEARED_TEXT, vectors.getProperty("cleared"));
	}

	@Test
	void firmwareCompletionRejectsChangedEpochOwnerPolicyAndResetNonce() throws Exception {
		var vectors = vectors();
		var protocol = protocol();
		String proof = vectors.getProperty("cleared");
		assertThat(protocol.verify(context(vectors, 0, OWNER, false, NONCE), proof)).isTrue();
		for (var changed : new Context[] {
			context(vectors, 1, OWNER, false, NONCE),
			context(vectors, 0, NEXT_OWNER, false, NONCE),
			context(vectors, 0, OWNER, true, NONCE),
			context(vectors, 0, OWNER, false, vectors.getProperty("deviceNonce"))}) {
			assertThat(protocol.verify(changed, proof)).isFalse();
		}
		assertThat(protocol.verify(context(vectors, 0, OWNER, false, NONCE), "malformed")).isFalse();
	}

	@Test
	void firmwareChallengeRequiresMatchingEpochOwnerAndUnalteredNonce() throws Exception {
		var vectors = vectors();
		var protocol = protocol();
		var challenge = challenge(vectors);
		var context = context(vectors, 1, NEXT_OWNER, false, NONCE);
		assertThat(protocol.verifyChallenge(context, challenge)).isTrue();
		assertThat(protocol.verifyChallenge(context(vectors, 0, NEXT_OWNER, false, NONCE), challenge)).isFalse();
		assertThat(protocol.verifyChallenge(context(vectors, 1, OWNER, false, NONCE), challenge)).isFalse();
		assertThat(protocol.verifyChallenge(context, new ResetChallenge(VERSION, "synthetic-key",
			"synthetic-device", 1L, NEXT_OWNER, challenge.challengeId(), NONCE, 60,
			challenge.signature()))).isFalse();
		assertThat(protocol.verifyChallenge(context, new ResetChallenge(VERSION, "synthetic-key",
			"synthetic-device", 1L, NEXT_OWNER, challenge.challengeId(), challenge.deviceNonce(), 61,
			challenge.signature()))).isFalse();
	}

	@Test
	void issuedBleJsonIsOneLineWithFirmwareFieldsAndIndependentlyVerifiableAuthorization() throws Exception {
		var vectors = vectors();
		var generator = KeyPairGenerator.getInstance("Ed25519");
		var keys = generator.generateKeyPair();
		var signer = new ServerSettingsSigner(keys.getPrivate(), keys.getPublic());
		var protocol = new SignedResetDeviceProtocol(signer);
		for (boolean discard : new boolean[] {false, true}) {
			String output = protocol.issue(context(vectors, 0, OWNER, discard, NONCE));
			assertThat(output).endsWith("\n").doesNotContain("\r");
			assertThat(output.chars().filter(value -> value == '\n').count()).isEqualTo(1);
			var json = JsonMapper.builder().build().readTree(output);
			assertThat(json.get("type").asText()).isEqualTo("RESET_DEVICE");
			assertThat(json.get("protocolVersion").asInt()).isEqualTo(1);
			assertThat(json.get("resetProtocolVersion").asText()).isEqualTo(VERSION);
			assertThat(json.get("serverKeyId").asText()).isEqualTo(signer.keyId());
			assertThat(json.get("keyId").asText()).isEqualTo("synthetic-key");
			assertThat(json.get("deviceSerial").asText()).isEqualTo("synthetic-device");
			assertThat(json.get("deviceId").asLong()).isEqualTo(4);
			assertThat(json.get("ownerGeneration").asText()).isEqualTo(OWNER);
			assertThat(json.get("requestId").asText()).isEqualTo(RUN);
			assertThat(json.get("resetRunId").asText()).isEqualTo(RUN);
			assertThat(json.get("fromOwnershipEpoch").asLong()).isZero();
			assertThat(json.get("toOwnershipEpoch").asLong()).isEqualTo(1);
			assertThat(json.get("challengeId").asText()).isEqualTo(vectors.getProperty("authChallengeId"));
			assertThat(json.get("deviceNonce").asText()).isEqualTo(vectors.getProperty("authDeviceNonce"));
			assertThat(json.get("resetNonce").asText()).isEqualTo(NONCE);
			assertThat(json.get("deletionScope").asText()).isEqualTo("OWNER_DATA_V1");
			String policy = discard ? "DISCARD_WITH_CONSENT" : "REQUIRE_SYNCED";
			assertThat(json.get("recordPolicy").asText()).isEqualTo(policy);
			String expected = AUTH_TEXT.replace("synthetic-server", signer.keyId())
				.replace("REQUIRE_SYNCED", policy);
			assertThat(verifies(keys.getPublic(), bytes(expected), json.get("serverSignature").asText())).isTrue();
		}
	}

