package com.e106.tingle.global.error;

import org.springframework.http.HttpStatus;

import com.e106.tingle.global.i18n.Messages;

import lombok.Getter;
import lombok.RequiredArgsConstructor;

/**
 * 앱에 내려가는 오류 코드. 앱은 이름(code)으로 분기하므로 이름을 바꾸면 팀 공유 API 계약도 함께 바꾼다.
 * 코드를 추가하면 resources/messages.properties 에 error.{코드} 문구도 추가한다(ErrorMessagesTest 가 확인).
 */
@Getter
@RequiredArgsConstructor
public enum ErrorCode {

	// 공통
	INVALID_REQUEST(HttpStatus.BAD_REQUEST),
	AUTH_REQUIRED(HttpStatus.UNAUTHORIZED),
	ONBOARDING_REQUIRED(HttpStatus.FORBIDDEN),
	FORBIDDEN(HttpStatus.FORBIDDEN),
	NOT_FOUND(HttpStatus.NOT_FOUND),
	INTERNAL_ERROR(HttpStatus.INTERNAL_SERVER_ERROR),
	SERVICE_UNAVAILABLE(HttpStatus.SERVICE_UNAVAILABLE),
	POLICY_UNRESOLVED(HttpStatus.UNPROCESSABLE_CONTENT),
	RATE_LIMITED(HttpStatus.TOO_MANY_REQUESTS),
	IDEMPOTENCY_CONFLICT(HttpStatus.CONFLICT),
	RESOURCE_NOT_FOUND(HttpStatus.NOT_FOUND),
	INVALID_AGE_RANGE(HttpStatus.BAD_REQUEST),
	PRECONDITION_REQUIRED(HttpStatus.PRECONDITION_REQUIRED),
	PRECONDITION_FAILED(HttpStatus.PRECONDITION_FAILED),

	// 키링 등록
	INVALID_DEVICE_PROOF(HttpStatus.UNPROCESSABLE_CONTENT),
	DEVICE_ALREADY_BOUND(HttpStatus.CONFLICT),
	SYNC_VERSION_STALE(HttpStatus.CONFLICT),
	SYNC_STORAGE_ACK_REQUIRED(HttpStatus.CONFLICT),
	OWNER_MISMATCH(HttpStatus.CONFLICT),
	OWNER_PROOF_EXPIRED(HttpStatus.GONE),
	OWNER_PERMISSION_DENIED(HttpStatus.FORBIDDEN),

	// 매칭 제안
	PROPOSAL_EXPIRED(HttpStatus.GONE),
	PROPOSAL_STATE_CONFLICT(HttpStatus.CONFLICT),
	PROFILE_CHANGED(HttpStatus.CONFLICT),
	CHAT_CLOSED(HttpStatus.GONE),
	AI_RISK_CONSENT_REQUIRED(HttpStatus.FORBIDDEN),
	INVALID_MESSAGE(HttpStatus.BAD_REQUEST),
	CHAT_NOTICE_REQUIRED(HttpStatus.FORBIDDEN),
	NOTICE_STATE_CONFLICT(HttpStatus.CONFLICT),
	PUSH_UNAVAILABLE(HttpStatus.SERVICE_UNAVAILABLE),

	// 소셜 로그인
	INVALID_PROVIDER(HttpStatus.BAD_REQUEST),
	INVALID_SOCIAL_TOKEN(HttpStatus.UNAUTHORIZED),
	SOCIAL_PROVIDER_ERROR(HttpStatus.BAD_GATEWAY),

	// 약관 동의
	REQUIRED_AGREEMENT_MISSING(HttpStatus.BAD_REQUEST),
	AGREEMENT_VERSION_OUTDATED(HttpStatus.CONFLICT),
	OPTIONAL_CONSENT_REQUIRED(HttpStatus.FORBIDDEN),

	// 프로필
	INVALID_NICKNAME(HttpStatus.BAD_REQUEST),
	INVALID_BIRTH_DATE(HttpStatus.BAD_REQUEST),
	INVALID_INTRODUCTION(HttpStatus.BAD_REQUEST),
	UNDER_AGE(HttpStatus.FORBIDDEN),
	NICKNAME_DUPLICATED(HttpStatus.CONFLICT),
	PROFILE_FIELD_LOCKED(HttpStatus.UNPROCESSABLE_CONTENT),
	PROFILE_INCOMPLETE(HttpStatus.BAD_REQUEST),

	// 프로필 사진
	PHOTO_INVALID(HttpStatus.BAD_REQUEST),
	PHOTO_REMOVED(HttpStatus.GONE),

	// 설문 응답
	INVALID_ANSWER(HttpStatus.UNPROCESSABLE_CONTENT),
	SESSION_COMPLETED(HttpStatus.CONFLICT),
	ANSWERS_INCOMPLETE(HttpStatus.CONFLICT),
	MIGRATION_UNSUPPORTED(HttpStatus.CONFLICT),
	MIGRATION_POLICY_CHANGED(HttpStatus.CONFLICT),

	// 성향 분석
	SESSION_NOT_COMPLETED(HttpStatus.CONFLICT),
	ANALYSIS_VERSION_UNSUPPORTED(HttpStatus.CONFLICT),

	// 개발용 휴대폰 만남
	PHONE_MODE_INVALID_PAYLOAD(HttpStatus.BAD_REQUEST),
	PHONE_MODE_FORBIDDEN(HttpStatus.FORBIDDEN),
	PHONE_MODE_NOT_FOUND(HttpStatus.NOT_FOUND),
	PHONE_MODE_DEVICE_CONFLICT(HttpStatus.CONFLICT),
	PHONE_MODE_IDEMPOTENCY_CONFLICT(HttpStatus.CONFLICT),
	PHONE_MODE_TOKEN_REUSED(HttpStatus.CONFLICT),
	PHONE_MODE_TOKEN_EXPIRED(HttpStatus.GONE),
	PHONE_MODE_INVALID_PROOF(HttpStatus.UNPROCESSABLE_CONTENT),
	PHONE_MODE_PAIR_UNAVAILABLE(HttpStatus.FORBIDDEN),

	// 규칙 관리(운영자)
	INVALID_RULE_DOCUMENT(HttpStatus.BAD_REQUEST),
	RULE_VERSION_CONFLICT(HttpStatus.CONFLICT),
	IMMUTABLE_VERSION(HttpStatus.CONFLICT),
	VALIDATION_STALE(HttpStatus.CONFLICT),
	APPROVAL_REQUIRED(HttpStatus.CONFLICT),
	SELF_APPROVAL_FORBIDDEN(HttpStatus.FORBIDDEN),
	RELEASE_NOT_PUBLISHED(HttpStatus.CONFLICT),
	CHANNEL_CHANGED(HttpStatus.CONFLICT),

	// 액세스 토큰 (앱 처리: EXPIRED 만 재발급 1회 시도, INVALID·SESSION_REVOKED 는 바로 로그인 화면)
	ACCESS_TOKEN_EXPIRED(HttpStatus.UNAUTHORIZED),
	ACCESS_TOKEN_INVALID(HttpStatus.UNAUTHORIZED),
	SESSION_REVOKED(HttpStatus.UNAUTHORIZED),

	// 회원탈퇴·분실 문의
	WITHDRAWAL_KEYRING_REGISTERED(HttpStatus.CONFLICT),
	WITHDRAWAL_RESET_PENDING(HttpStatus.CONFLICT),
	WITHDRAWAL_OPERATION_EXPIRED(HttpStatus.GONE),
	KEYRING_PERMANENTLY_BLOCKED(HttpStatus.CONFLICT),
	REAUTHENTICATION_REQUIRED(HttpStatus.FORBIDDEN),
	CASE_STATE_CONFLICT(HttpStatus.CONFLICT),

	// 토큰 재발급·로그아웃
	INVALID_REFRESH_TOKEN(HttpStatus.UNAUTHORIZED);

	private final HttpStatus status;

	/**
	 * 현재 요청 언어(Accept-Language)의 사용자 표시 문구.
	 */
	public String getMessage() {
		return Messages.get("error." + name());
	}
}
